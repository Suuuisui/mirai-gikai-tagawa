/** 見出し語と表記ゆれをまとめて、検出に使う語の一覧にする */
export function glossaryWords(entry: GlossaryEntry): string[] {
  return [entry.term, ...(entry.aliases ?? [])];
}

/**
 * 本文に登場することばだけを抽出する。
 * 表示順は GLOSSARY の定義順（重要度順）を保つ
 */
export function pickGlossaryTerms(texts: string[]): GlossaryEntry[] {
  const haystack = texts.join("\n");
  return GLOSSARY.filter((entry) =>
    glossaryWords(entry).some((word) => haystack.includes(word))
  );
}
