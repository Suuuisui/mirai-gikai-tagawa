/**
 * 会議の要約・要点・議題に登場する用語だけを抽出する。
 * 表示順は COMMITTEE_GLOSSARY の定義順（重要度順）を保つ
 */
export function pickGlossaryTerms(texts: string[]): GlossaryTerm[] {
  const haystack = texts.join("\n");
  return COMMITTEE_GLOSSARY.filter((entry) =>
    [entry.term, ...(entry.aliases ?? [])].some((word) =>
      haystack.includes(word)
    )
  );
}
